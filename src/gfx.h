/* Minimal 32bpp drawing for the 320x240 LCD (no external deps). */
#ifndef TDX_GFX_H
#define TDX_GFX_H

#include <stdint.h>

struct tdx_fb {
	int w, h;
	uint32_t *px; /* 0x00RRGGBB, row-major */
};

void gfx_fill(struct tdx_fb *fb, int x, int y, int w, int h, uint32_t c);
/* Draw text with the built-in 5x7 font scaled by @scale. Returns end x. */
int gfx_text(struct tdx_fb *fb, int x, int y, const char *s, int scale, uint32_t c);
int gfx_text_width(const char *s, int scale);

/* Load binary PPM (P6, maxval<=255) into a 320x240 fb (cropped / padded). */
int gfx_load_ppm(struct tdx_fb *fb, const char *path);

/* Anti-aliased text (font_aa.c, generated by tools/gen_font.py). */
struct gfx_glyph {
	int adv, x, y, w, h; /* advance, ink box relative to the pen at the line top */
	unsigned off;        /* into the font's alpha data */
};
struct gfx_font {
	int px, ascent, height;
	const struct gfx_glyph *g; /* ASCII 32..126 */
	const uint8_t *alpha;
};
extern const struct gfx_font gfx_font_f12, gfx_font_f14, gfx_font_f14b, gfx_font_f18b,
	gfx_font_f24b;
/* Draw @s with its line top at y; non-ASCII bytes are skipped. Returns end x. */
int gfx_text_aa(struct tdx_fb *fb, int x, int y, const char *s, const struct gfx_font *f,
		uint32_t c);
int gfx_text_aa_width(const char *s, const struct gfx_font *f);

/* RGBA images (premultiplied: no; straight alpha), loaded from PAM (P7 RGB_ALPHA
 * or RGB) files written by tools/extract_3dxware_ui.py. */
struct gfx_img {
	int w, h;
	uint8_t *rgba;
};
int gfx_load_pam(struct gfx_img *img, const char *path); /* 0 or -errno */
void gfx_img_free(struct gfx_img *img);
/* Alpha-blend @img (or its sub-rectangle sx,sy,sw,sh) at x,y; clipped to the fb. */
void gfx_blit(struct tdx_fb *fb, const struct gfx_img *img, int x, int y);
void gfx_blit_part(struct tdx_fb *fb, const struct gfx_img *img, int sx, int sy, int sw, int sh,
		   int x, int y);
/* Vertical gradient from c0 (top) to c1 (bottom). */
void gfx_vgradient(struct tdx_fb *fb, int x, int y, int w, int h, uint32_t c0, uint32_t c1);

#endif
