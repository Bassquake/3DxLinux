"""Generate src/font_aa.c: anti-aliased glyph tables for the LCD (ASCII 32..126).

Rendered once with Pango/Cairo from DejaVu Sans (Bitstream Vera / DejaVu
license: free to embed and redistribute, see the notice in the output), so the
daemon draws smooth text with no font library at run time.

    tools/gen_font.py > src/font_aa.c
"""
import sys

import gi

gi.require_version("Pango", "1.0")
gi.require_version("PangoCairo", "1.0")
from gi.repository import Pango, PangoCairo  # noqa: E402
import cairo  # noqa: E402

FAMILY = "DejaVu Sans"
SIZES = [(12, False), (14, False), (14, True), (18, True), (24, True)]  # pixel sizes, bold


def render(px, bold):
    glyphs, data = [], bytearray()
    fd = Pango.FontDescription("%s %s %dpx" % (FAMILY, "Bold" if bold else "", px))
    surf = cairo.ImageSurface(cairo.FORMAT_A8, 4 * px, 2 * px)
    for ch in range(32, 127):
        cr = cairo.Context(surf)
        cr.set_operator(cairo.OPERATOR_CLEAR)
        cr.paint()
        cr.set_operator(cairo.OPERATOR_OVER)
        lay = PangoCairo.create_layout(cr)
        fo = cairo.FontOptions()
        fo.set_antialias(cairo.ANTIALIAS_GRAY)
        fo.set_hint_style(cairo.HINT_STYLE_SLIGHT)
        PangoCairo.context_set_font_options(lay.get_context(), fo)
        lay.set_font_description(fd)
        lay.set_text(chr(ch), -1)
        ink, logical = lay.get_pixel_extents()
        cr.move_to(px, 0)
        PangoCairo.show_layout(cr, lay)
        surf.flush()
        buf, stride = surf.get_data(), surf.get_stride()
        # bounding box of the inked pixels
        xs = [x for y in range(surf.get_height()) for x in range(surf.get_width())
              if buf[y * stride + x]]
        ys = [y for y in range(surf.get_height()) for x in range(surf.get_width())
              if buf[y * stride + x]]
        adv = logical.width
        if not xs:
            glyphs.append((adv, 0, 0, 0, 0, len(data)))
            continue
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        off = len(data)
        for y in range(y0, y1 + 1):
            data += bytes(buf[y * stride + x0:y * stride + x1 + 1])
        glyphs.append((adv, x0 - px, y0, x1 - x0 + 1, y1 - y0 + 1, off))
    asc = lay.get_baseline() // Pango.SCALE
    height = logical.height
    return glyphs, data, asc, height


def main():
    out = sys.stdout
    out.write("/* Generated by tools/gen_font.py: DejaVu Sans, anti-aliased, ASCII 32..126.\n"
              " * DejaVu fonts: Bitstream Vera Fonts Copyright (c) 2003 Bitstream, Inc.;\n"
              " * DejaVu changes are in the public domain. Glyph data may be embedded and\n"
              " * redistributed (Bitstream Vera license). */\n")
    out.write('#include "gfx.h"\n\n')
    names = []
    for px, bold in SIZES:
        g, data, asc, height = render(px, bold)
        n = "f%d%s" % (px, "b" if bold else "")
        names.append(n)
        out.write("static const uint8_t %s_px[%d] = {\n" % (n, max(1, len(data))))
        for i in range(0, len(data), 24):
            out.write("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        out.write("};\n")
        out.write("static const struct gfx_glyph %s_g[95] = {\n" % n)
        for adv, x, y, w, h, off in g:
            out.write("\t{%d, %d, %d, %d, %d, %d},\n" % (adv, x, y, w, h, off))
        out.write("};\n")
        out.write("const struct gfx_font gfx_font_%s = {%d, %d, %d, %s_g, %s_px};\n\n"
                  % (n, px, asc, height, n, n))


if __name__ == "__main__":
    main()
