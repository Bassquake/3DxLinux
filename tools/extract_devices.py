#!/usr/bin/env python3
"""Generate src/devices_gen.c from the 3DxWare device database.

The Windows 3DxWare installer ships a data-driven device table in
``Base.xml`` (installed under ``3DxWinCore64.msi`` -> Data1.cab, file key
``_947C11BD496D42BF96E41E7C37165A55``).  Every ``<Device>`` element lists the
USB VID/PID, device class, and for each physical button the HID report it
arrives in plus either a bitmask (``<Mask>``), a button number
(``<Number>``, used by report 0x1C devices) or a long-press mask
(``<LongPressMask>``, report 0x1D).

This script turns that into a static C table so the Linux daemon needs no XML
parser at runtime and no 3Dconnexion files on the target machine.

Usage:
    python3 tools/extract_devices.py path/to/Base.xml > src/devices_gen.c
"""
import sys
import xml.etree.ElementTree as ET

CLASS_MAP = {
    "SI_CLASS_3DMOUSE": "TDX_CLASS_3DMOUSE",
    "SI_CLASS_2DMOUSE": "TDX_CLASS_2DMOUSE",
    "SI_CLASS_KEYBOARD": "TDX_CLASS_KEYBOARD",
    "SI_CLASS_WIRELESS_RECEIVER": "TDX_CLASS_RECEIVER",
    "SI_CLASS_UNIVERSAL_WIRELESS_RECEIVER": "TDX_CLASS_RECEIVER",
}

# Facts from 3dxhid.inf / LGPBTDD.inf in the same installer: which USB
# interface carries the HID collection, and which devices have the QVGA LCD
# (bound to Logitech's LGPBTDD.sys on interface 0).
HID_IFACE = {0xC629: 1, 0xC633: 1, 0xC63C: 1, 0xC650: 1, 0xC651: 1,
             0xC654: 1, 0xC655: 1, 0xC656: 1, 0xC657: 1, 0xC658: 1}
LCD_KIND = {(0x046D, 0xC629): "TDX_LCD_QVGA",    # LGPBTDD.inf (Logitech G19-class)
            (0x256F, 0xC633): "TDX_LCD_ENT640",  # HIDDev.dll CWinUSBLCDMgr
            (0x256F, 0xC63C): "TDX_LCD_GIO1280"} # HIDDev.dll DAT_1800de3e0 descriptor

# Devices older than this 3DxWare release (absent from Base.xml).  Their IDs
# are publicly documented; buttons are exposed generically (bit n -> n+1).
LEGACY = [
    (0x046D, 0xC603, "ID_Legacy_C603", "SpaceMouse Plus XT (USB)", 0),
    (0x046D, 0xC605, "ID_Legacy_C605", "CADman", 0),
    (0x046D, 0xC606, "ID_Legacy_C606", "SpaceMouse Classic (USB)", 0),
    (0x046D, 0xC621, "ID_Legacy_C621", "SpaceBall 5000 (USB)", 12),
    (0x046D, 0xC623, "ID_Legacy_C623", "SpaceTraveler", 8),
    (0x046D, 0xC625, "ID_Legacy_C625", "SpacePilot", 21),
    (0x046D, 0xC627, "ID_Legacy_C627", "SpaceExplorer", 15),
]


def cstr(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def hexint(s, default=0):
    s = (s or "").strip()
    return int(s, 16) if s else default


def main(path):
    root = ET.parse(path).getroot()
    devs = {d.findtext("ID"): d for d in root.iter("Device")}

    def own_buttons(d):
        out = []
        for b in d.findall("ButtonInfo/Button"):
            ev = b.find("Event")
            if ev is None or ev.findtext("ReportID") is None:
                continue
            rid = hexint(ev.findtext("ReportID"))
            mask, num, lp = ev.findtext("Mask"), ev.findtext("Number"), ev.findtext("LongPressMask")
            if lp is not None:
                kind, value, lpm = "TDX_BTN_LONGPRESS", int(num or 0), hexint(lp)
            elif num is not None:
                kind, value, lpm = "TDX_BTN_NUMBER", int(num), 0
            else:
                kind, value, lpm = "TDX_BTN_MASK", hexint(mask), 0
            led = b.findtext("LEDNumber")
            out.append((rid, kind, value, lpm, int(led) if led is not None else -1,
                        b.findtext("ButtonID"), b.findtext("V3DKID"), b.findtext("Label")))
        return out

    def resolved_buttons(d, depth=0):
        btns = own_buttons(d)
        parent = d.findtext("InheritsFromID")
        if not btns and parent and parent in devs and depth < 8:
            return resolved_buttons(devs[parent], depth + 1)
        return btns

    print("/* AUTO-GENERATED by tools/extract_devices.py from 3DxWare Base.xml. Do not edit. */")
    print('#include "devices.h"\n#include <stddef.h>\n')
    entries = []
    for did, d in devs.items():
        vid, pid = hexint(d.findtext("VendorID")), hexint(d.findtext("ProductID"))
        if vid == 0 or did == "ID_PseudoDevice":
            continue
        btns = resolved_buttons(d)
        sym = "btn_" + did.replace("ID_", "").lower()
        if btns:
            print(f"static const struct tdx_button_def {sym}[] = {{")
            for rid, kind, value, lpm, led, bid, v3dk, label in btns:
                print(f"  {{0x{rid:02X}, {kind}, 0x{value:08X}u, 0x{lpm:08X}u, {led}, "
                      f"{cstr(bid)}, {cstr(v3dk)}, {cstr(label)}}},")
            print("};\n")
        entries.append((vid, pid, did, d.findtext("Name"),
                        CLASS_MAP.get(d.findtext("Class"), "TDX_CLASS_UNKNOWN"),
                        sym if btns else "NULL", len(btns)))

    print("const struct tdx_device_def tdx_devices[] = {")
    for vid, pid, did, name, cls, sym, n in entries:
        lcd = LCD_KIND.get((vid, pid), "TDX_LCD_NONE")
        print(f"  {{0x{vid:04X}, 0x{pid:04X}, {cstr(did)}, {cstr(name)}, {cls}, {lcd}, "
              f"{HID_IFACE.get(pid, 0)}, {sym}, {n}}},")
    print("  /* legacy devices not present in this 3DxWare release */")
    for vid, pid, did, name, nb in LEGACY:
        print(f"  {{0x{vid:04X}, 0x{pid:04X}, {cstr(did)}, {cstr(name)}, TDX_CLASS_3DMOUSE, "
              f"TDX_LCD_NONE, 0, NULL, 0}},")
    print("};\n")
    print("const size_t tdx_device_count = sizeof(tdx_devices) / sizeof(tdx_devices[0]);")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
